"""'What changed in the newer version': this repo's files (2016) against my-first-blog at the commit stored in
web/data/newer_snapshot.json (made by scripts/make_newer_snapshot.py). Line diffs come from difflib; the
structural summary (views, URL patterns, templates, settings) from ast and plain text matching.
"""
import ast
import difflib
import json
import re
from functools import lru_cache
from pathlib import Path

from . import code_index

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "web" / "data" / "newer_snapshot.json"
SECRET_LINE = re.compile(r"^SECRET_KEY = .*$", re.M)


# Lines this repo gained only for the web interface (2026), left out so the diff shows the 2016 code.
WEB_ONLY_LINES = {".gitignore": {"site/"}}


def normalise(text: str, path: str = "") -> str:
    """Both versions hide SECRET_KEY the same way, so the diff shows code changes, not key handling."""
    skip = WEB_ONLY_LINES.get(path)
    if skip:
        text = "".join(ln for ln in text.splitlines(keepends=True) if ln.strip() not in skip)
    return SECRET_LINE.sub("SECRET_KEY = <not shown>", text)


@lru_cache(maxsize=1)
def snapshot() -> dict:
    return json.loads(SNAPSHOT.read_text())


def old_files() -> dict:
    out = {}
    for p in code_index.files():
        rel = p.relative_to(ROOT).as_posix()
        if code_index.group(rel).startswith("Django app"):
            out[rel] = p.read_text()
    return out


def _hunks(a: str, b: str, context: int = 3) -> list:
    al, bl = a.splitlines(), b.splitlines()
    out = []
    for group in difflib.SequenceMatcher(None, al, bl, autojunk=False).get_grouped_opcodes(context):
        lines = []
        for tag, i1, i2, j1, j2 in group:
            if tag == "equal":
                lines += [[" ", al[i], i + 1, j1 + k + 1] for k, i in enumerate(range(i1, i2))]
                continue
            lines += [["-", al[i], i + 1, None] for i in range(i1, i2)]
            lines += [["+", bl[j], None, j + 1] for j in range(j1, j2)]
        f, l = group[0], group[-1]
        out.append({"header": f"@@ -{f[1] + 1},{l[2] - f[1]} +{f[3] + 1},{l[4] - f[3]} @@", "lines": lines})
    return out


def file_changes() -> list:
    old, new = old_files(), snapshot()["files"]
    out = []
    for path in sorted(set(old) | set(new)):
        a, b = normalise(old.get(path, ""), path), normalise(new.get(path, ""), path)
        status = "added" if path not in old else "removed" if path not in new else "same" if a == b else "modified"
        hunks = _hunks(a, b) if status != "same" else []
        add = sum(1 for h in hunks for x in h["lines"] if x[0] == "+")
        rem = sum(1 for h in hunks for x in h["lines"] if x[0] == "-")
        out.append({"path": path, "status": status, "added": add, "removed": rem,
                    "old_lines": len(a.splitlines()), "new_lines": len(b.splitlines()), "hunks": hunks})
    return out


def _functions(src):
    return [n.name for n in ast.parse(src).body if isinstance(n, ast.FunctionDef)] if src else []


def _url_regexes(src):
    return [n.args[0].value for n in ast.walk(ast.parse(src)) if isinstance(n, ast.Call) and n.args
            and isinstance(n.args[0], ast.Constant) and isinstance(n.args[0].value, str)
            and getattr(n.func, "id", getattr(n.func, "attr", "")) == "url"] if src else []


def _settings(src):
    out = {}
    for n in ast.parse(src).body:
        if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name) and n.targets[0].id.isupper():
            out[n.targets[0].id] = "<not shown>" if n.targets[0].id == "SECRET_KEY" else ast.get_source_segment(src, n.value)
    return out


def _generated(src):
    m = re.search(r"(?:Generated by|using) (?:'django-admin startproject' using )?Django (\d+(?:\.\d+)*)", src or "")
    return m.group(1) if m else None


def structure() -> dict:
    old, new = old_files(), snapshot()["files"]
    so, sn = _settings(old["mysite/settings.py"]), _settings(new["mysite/settings.py"])
    settings = [{"name": k, "old": so.get(k), "new": sn.get(k)} for k in sorted(set(so) | set(sn))
                if so.get(k) != sn.get(k) and k != "SECRET_KEY"]
    tmpl = lambda files: sorted(p.rsplit("/", 1)[1] for p in files if p.startswith("blog/templates/"))
    return {
        "django_version": {"old": _generated(old["mysite/settings.py"]), "new": _generated(new["mysite/settings.py"]),
                           "old_migration": _generated(old["blog/migrations/0001_initial.py"]),
                           "new_migration": _generated(new["blog/migrations/0001_initial.py"])},
        "views": {"old": _functions(old.get("blog/views.py")), "new": _functions(new.get("blog/views.py"))},
        "urls": {"old": _url_regexes(old.get("blog/urls.py")), "new": _url_regexes(new.get("blog/urls.py"))},
        "templates": {"old": tmpl(old), "new": tmpl(new)},
        "model_same": normalise(old["blog/models.py"]) == normalise(new["blog/models.py"]),
        "settings": settings,
    }


def changes() -> dict:
    snap = snapshot()
    files = file_changes()
    counts = {s: sum(f["status"] == s for f in files) for s in ("added", "removed", "modified", "same")}
    return {"newer": {"repo": snap["repo"], "commit": snap["short"], "log": snap["log"]}, "old_log": snap["old_log"],
            "counts": counts, "lines_added": sum(f["added"] for f in files),
            "lines_removed": sum(f["removed"] for f in files), "files": files, "structure": structure()}
