// What changed in the newer version: /api/changes (web/changes.py: difflib line diffs + ast structure) between this
// repo's files and gddickinson/my-first-blog at a fixed commit. #/changes/<path> jumps to one file's diff.
import { api, app, esc, list, route } from './core.js';

const side = (title, old, now) => {
  const gone = old.filter(x => !now.includes(x)), added = now.filter(x => !old.includes(x));
  return `<div class="panel"><h3>${esc(title)}</h3><div class="cmp">
    <div><p class="small mute">2016</p>${list(old, x => `<div class="mono small ${gone.includes(x) ? 'st-removed' : ''}">${esc(x || "''")}</div>`)}</div>
    <div><p class="small mute">newer</p>${list(now, x => `<div class="mono small ${added.includes(x) ? 'st-added' : ''}">${added.includes(x) ? '+ ' : ''}${esc(x || "''")}</div>`)}</div>
  </div></div>`;
};

function diffBlock(f) {
  if (!f.hunks.length) return '<p class="mute small">No differences.</p>';
  return list(f.hunks, h => `<div class="diff"><div class="hh">${esc(h.header)}</div>${list(h.lines, ([op, text, a, b]) =>
    `<div class="dl ${op === '+' ? 'add' : op === '-' ? 'del' : ''}"><span class="n">${a ?? ''}</span><span class="n">${b ?? ''}</span><code>${esc(op + ' ' + text)}</code></div>`)}</div>`);
}

route('changes', async (args) => {
  const c = await api('/changes');
  const s = c.structure, focus = args.join('/');
  app().innerHTML = `
  <p class="kicker">2016 &rarr; December 2017</p><h1>What changed in the newer version</h1>
  <p class="lead">This repository's Django app compared with
    <a href="https://github.com/gddickinson/my-first-blog/tree/${esc(c.newer.commit)}">${esc(c.newer.repo)} at ${esc(c.newer.commit)}</a>,
    file by file. Computed from the real files by <code>web/changes.py</code>; <code>SECRET_KEY</code> lines are hidden on both sides.</p>
  <div class="tiles">
    <div class="tile"><b>${c.counts.modified}</b><span>files modified</span></div>
    <div class="tile"><b>${c.counts.added}</b><span>files added</span></div>
    <div class="tile"><b>${c.counts.same}</b><span>files unchanged</span></div>
    <div class="tile"><b>+${c.lines_added}</b><span>lines added</span></div>
    <div class="tile"><b>-${c.lines_removed}</b><span>lines removed</span></div>
    <div class="tile"><b>${esc(s.django_version.old)} &rarr; ${esc(s.django_version.new)}</b><span>Django (startproject header)</span></div>
  </div>
  <h2>In short</h2>
  <div class="two">
    ${side('Views (blog/views.py)', s.views.old, s.views.new)}
    ${side('URL patterns (blog/urls.py)', s.urls.old, s.urls.new)}
    ${side('Templates', s.templates.old, s.templates.new)}
    <div class="panel"><h3>Model</h3><p class="small">${s.model_same ? '<code>blog/models.py</code> is identical in both: the Post model was already written in 2016.' : '<code>blog/models.py</code> differs (see below).'}</p>
      <p class="small">Migration generated by Django ${esc(s.django_version.old_migration)} &rarr; ${esc(s.django_version.new_migration)}.</p></div>
  </div>
  <h3>Settings that differ</h3>
  <div class="scroll"><table><thead><tr><th>Setting</th><th>2016</th><th>newer</th></tr></thead><tbody>
    ${list(s.settings, x => `<tr><td><code>${esc(x.name)}</code></td><td class="mono small">${esc(x.old ?? '(not set)')}</td><td class="mono small">${esc(x.new ?? '(not set)')}</td></tr>`)}
  </tbody></table></div>
  <h2>Files</h2>
  <div class="scroll"><table><thead><tr><th>File</th><th>Status</th><th>Lines</th></tr></thead><tbody>
    ${list(c.files, f => `<tr><td class="mono"><a href="#/changes/${esc(f.path)}">${esc(f.path)}</a></td>
      <td class="st-${f.status}">${f.status === 'same' ? 'unchanged' : f.status}</td>
      <td class="mono small">${f.status === 'same' ? f.old_lines : `<span class="st-added">+${f.added}</span> <span class="st-removed">-${f.removed}</span>`}</td></tr>`)}
  </tbody></table></div>
  <h2>Diffs</h2>
  ${list(c.files.filter(f => f.status !== 'same'), f => `<details id="d-${esc(f.path.replace(/[^A-Za-z0-9]+/g, '-'))}" ${f.path === focus || f.path.endsWith('views.py') || f.path.endsWith('urls.py') && f.path.startsWith('blog') ? 'open' : ''}>
    <summary class="mono" style="cursor:pointer;padding:6px 0"><span class="st-${f.status}">${f.status}</span> ${esc(f.path)}</summary>${diffBlock(f)}</details>`)}`;
  if (focus) app().querySelector('#d-' + focus.replace(/[^A-Za-z0-9]+/g, '-'))?.scrollIntoView();
});
